const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  );

const purposeOf = (file) => PURPOSE.find(([pattern]) => pattern.test(file))?.[1] ?? '';
const kb = (bytes) => (bytes / 1024).toFixed(1);

async function imageRow(file) {
  const meta = await sharp(file).metadata();
  const { isOpaque } = await sharp(file).stats();
  const alpha = !meta.hasAlpha ? 'none' : isOpaque ? 'channel, all opaque' : 'yes';
  const css = `${meta.width / 2}x${meta.height / 2}`;
  return `| ${file} | ${meta.format} | ${meta.width}x${meta.height} | ${css} | ${kb(statSync(file).size)} | ${alpha} | ${purposeOf(file)} |`;
}

function audioRow(file) {
  const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration,bit_rate:stream=channels', '-of', 'json', file]);
  const { format, streams } = JSON.parse(out);
  const details = `${Number(format.duration).toFixed(1)} s, ${Math.round(format.bit_rate / 1000)} kbps, ${streams[0].channels} ch`;
  return `| ${file} | mp3 | ${details} | | ${kb(statSync(file).size)} | n/a | ${purposeOf(file)} |`;
}

const HEADER = '| File | Format | Pixels / audio | CSS px | KB | Alpha | Purpose |\n|---|---|---|---|---|---|---|';

async function section(title, dir) {
  const files = walk(dir).filter((file) => !file.endsWith('.DS_Store')).sort();
  const rows = [];
  for (const file of files) {
    rows.push(extname(file) === '.mp3' ? audioRow(file) : await imageRow(file));
  }
  const total = files.reduce((sum, file) => sum + statSync(file).size, 0);
  return `## ${title}\n\n${files.length} files, ${kb(total)} KB in total.\n\n${HEADER}\n${rows.join('\n')}\n`;
}

const doc = [
  '# Asset inventory',
  '',
  'Generated by `npm run assets:report`. Do not edit by hand.',
  '',
  'Alpha "none" means the file has no alpha channel, so its black areas are opaque.',
  '',
  await section('Variant A', 'variant-a-game/assets'),
  await section('Variant B', 'variant-b-fireplace/assets'),
].join('\n');

writeFileSync('docs/ASSETS.md', doc);
